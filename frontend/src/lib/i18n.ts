export type TranslationKey = keyof typeof translations.en;

export function t(
  lang: LanguageOption | undefined,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  const effectiveLang: LanguageOption = lang && translations[lang] ? lang : 'en';
  let str: string = (translations[effectiveLang] as any)?.[key] || translations.en[key] || String(key);

  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }

  return str;
}

export function useTranslation(lang: LanguageOption | undefined) {
  const currentLang = lang || 'en';
  return {
    t: (key: TranslationKey, params?: Record<string, string | number>) => t(currentLang, key, params),
    lang: currentLang,
  };
}
